BEGIN;

-- -----------------------------------------------------------------------------
-- 1. whatsapp_identities
--    Links a WhatsApp phone number to the canonical TrustHub identity
--    (profiles/auth.users). Not a parallel/permanent identity system —
--    profile_id is nullable only for the brief instant before identity
--    resolution completes (Final Migration Spec Section F).
-- -----------------------------------------------------------------------------

CREATE TABLE whatsapp_identities (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone_number text NOT NULL,
  profile_id   bigint NULL REFERENCES profiles(id) ON DELETE SET NULL,
  linked_at    timestamptz NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT whatsapp_identities_phone_number_key UNIQUE (phone_number),
  -- Allows multiple NULLs (not-yet-linked rows) but at most one linked
  -- WhatsApp number per profile — the enforced expression of
  -- "one person, one TrustHub identity."
  CONSTRAINT whatsapp_identities_profile_id_key UNIQUE (profile_id)
);

COMMENT ON TABLE whatsapp_identities IS
  'Link table only: WhatsApp phone number -> canonical profiles/auth.users identity. See docs/TRUSTHUB_CONNECT_FINAL_MIGRATION_SPEC.md Section F.';

-- -----------------------------------------------------------------------------
-- 2. conversations
--    Channel-agnostic session container. WhatsApp is one channel value,
--    not the whole architecture (Section G).
-- -----------------------------------------------------------------------------

CREATE TABLE conversations (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel              text NOT NULL DEFAULT 'whatsapp',
  whatsapp_identity_id bigint NULL REFERENCES whatsapp_identities(id) ON DELETE SET NULL,
  profile_id           bigint NULL REFERENCES profiles(id) ON DELETE SET NULL,
  community_id         uuid NULL REFERENCES communities(id) ON DELETE SET NULL,
  area                 text NULL,
  status               text NOT NULL DEFAULT 'open',
  started_at           timestamptz NOT NULL DEFAULT now(),
  last_message_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversations_channel_check
    CHECK (channel IN ('whatsapp', 'web', 'admin', 'system')),
  CONSTRAINT conversations_status_check
    CHECK (status IN ('open', 'awaiting_agent', 'resolved', 'abandoned'))
);

CREATE INDEX conversations_profile_id_idx ON conversations (profile_id);
CREATE INDEX conversations_whatsapp_identity_id_idx ON conversations (whatsapp_identity_id);
CREATE INDEX conversations_community_id_idx ON conversations (community_id);
CREATE INDEX conversations_status_idx ON conversations (status);

COMMENT ON TABLE conversations IS
  'Channel-agnostic conversation/session container. See docs/TRUSTHUB_CONNECT_FINAL_MIGRATION_SPEC.md Section G.';

-- -----------------------------------------------------------------------------
-- 3. conversation_messages
--    Individual message history, with webhook-redelivery idempotency
--    (provider_message_id) — Final Migration Spec Section A1.
-- -----------------------------------------------------------------------------

CREATE TABLE conversation_messages (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id     bigint NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  channel             text NOT NULL,
  direction           text NOT NULL,
  sender              text NOT NULL,
  content             text NOT NULL,
  metadata            jsonb NULL,
  provider_message_id text NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversation_messages_channel_check
    CHECK (channel IN ('whatsapp', 'web', 'admin', 'system')),
  CONSTRAINT conversation_messages_direction_check
    CHECK (direction IN ('inbound', 'outbound')),
  CONSTRAINT conversation_messages_sender_check
    CHECK (sender IN ('user', 'ai_agent', 'trust_agent', 'system')),
  -- Nullable-safe unique index: multiple NULLs allowed (outbound/system
  -- messages with no provider identifier); redelivered webhooks with the
  -- same provider_message_id are rejected as duplicates.
  CONSTRAINT conversation_messages_provider_message_id_key UNIQUE (provider_message_id)
);

CREATE INDEX conversation_messages_conversation_id_created_at_idx
  ON conversation_messages (conversation_id, created_at);

COMMENT ON TABLE conversation_messages IS
  'Individual message history. provider_message_id gives webhook-redelivery idempotency (INSERT ... ON CONFLICT (provider_message_id) DO NOTHING at the application layer). See Section A1/G.';

-- -----------------------------------------------------------------------------
-- 4. contributions
--    Single, generalized knowledge/provenance record — capability
--    declarations, community recommendations, and general local
--    information that business_information_updates structurally cannot
--    represent (Sections H, I). Distinct from, and linked to,
--    help_requests (asks) and business_information_updates (business-field
--    corrections) — never merged with either.
-- -----------------------------------------------------------------------------

CREATE TABLE contributions (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contributor_profile_id    bigint NOT NULL REFERENCES profiles(id) ON DELETE RESTRICT,
  category                  text NULL,
  claim_text                text NOT NULL,
  business_id               uuid NULL REFERENCES businesses(id) ON DELETE SET NULL,
  provider_name             text NULL,
  community_id              uuid NULL REFERENCES communities(id) ON DELETE SET NULL,
  area                      text NULL,
  source                    text NOT NULL,
  relationship              text NULL,
  evidence_notes            text NULL,
  verification_status       text NOT NULL DEFAULT 'declared',
  reviewed_by_profile_id    bigint NULL REFERENCES profiles(id) ON DELETE SET NULL,
  reviewed_at               timestamptz NULL,
  related_conversation_id   bigint NULL REFERENCES conversations(id) ON DELETE SET NULL,
  related_help_request_id   uuid NULL REFERENCES help_requests(id) ON DELETE SET NULL,
  source_message_id         bigint NULL REFERENCES conversation_messages(id) ON DELETE SET NULL,
  subject_type              text NOT NULL,
  created_at                timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT contributions_verification_status_check
    CHECK (verification_status IN ('verified', 'observed', 'declared', 'inferred', 'potential', 'unknown')),
  CONSTRAINT contributions_subject_type_check
    CHECK (subject_type IN ('business', 'self', 'named_provider', 'general_info'))
);

CREATE INDEX contributions_contributor_profile_id_idx ON contributions (contributor_profile_id);
CREATE INDEX contributions_business_id_idx ON contributions (business_id);
CREATE INDEX contributions_community_id_idx ON contributions (community_id);
CREATE INDEX contributions_verification_status_idx ON contributions (verification_status);
CREATE INDEX contributions_related_conversation_id_idx ON contributions (related_conversation_id);
CREATE INDEX contributions_related_help_request_id_idx ON contributions (related_help_request_id);

COMMENT ON TABLE contributions IS
  'Generalized knowledge/provenance record: self-declared capability, community-recommended provider, or general info. Not a business-field correction log (that remains business_information_updates, untouched) and not a request (that remains help_requests, extended below). See Section H.';

-- -----------------------------------------------------------------------------
-- 5. Extend existing help_requests (Section C) — additive only.
--    No existing column is renamed, retyped, or dropped. `requester_id`,
--    `status`, `resolved_at`, `title`, `description`, `latitude`,
--    `longitude`, `community_id`, `created_at` are all reused exactly as
--    they already exist.
-- -----------------------------------------------------------------------------

ALTER TABLE help_requests
  ADD COLUMN conversation_id bigint NULL REFERENCES conversations(id) ON DELETE SET NULL,
  ADD COLUMN requested_category text NULL,
  ADD COLUMN intent text NULL,
  ADD COLUMN area text NULL,
  ADD COLUMN matched_business_id uuid NULL REFERENCES businesses(id) ON DELETE SET NULL,
  ADD COLUMN matched_contribution_id bigint NULL REFERENCES contributions(id) ON DELETE SET NULL,
  ADD COLUMN source_channel text NULL DEFAULT 'web';

ALTER TABLE help_requests
  ADD CONSTRAINT help_requests_intent_check
    CHECK (intent IS NULL OR intent IN ('find_business', 'find_provider', 'ask_question', 'report_issue')),
  ADD CONSTRAINT help_requests_source_channel_check
    CHECK (source_channel IS NULL OR source_channel IN ('whatsapp', 'web', 'admin', 'system')),
  -- Cross-column check only (B2) — does NOT constrain the existing
  -- `status` column's value space, which remains an unconstrained,
  -- pre-existing text column by deliberate choice (Section C).
  ADD CONSTRAINT help_requests_resolved_at_check
    CHECK (status <> 'resolved' OR resolved_at IS NOT NULL);

CREATE INDEX help_requests_conversation_id_idx ON help_requests (conversation_id);
CREATE INDEX help_requests_matched_business_id_idx ON help_requests (matched_business_id);
CREATE INDEX help_requests_matched_contribution_id_idx ON help_requests (matched_contribution_id);
CREATE INDEX help_requests_community_id_requested_category_idx
  ON help_requests (community_id, requested_category);

COMMENT ON COLUMN help_requests.conversation_id IS
  'Added by TrustHub Connect migration 001 — links a WhatsApp-originated request to its conversation.';
COMMENT ON COLUMN help_requests.source_channel IS
  'Added by TrustHub Connect migration 001 — distinguishes which channel originated the request (default ''web'' preserves prior/implicit behavior for any existing usage).';

-- -----------------------------------------------------------------------------
-- 6. Row Level Security — NEW TABLES ONLY.
--    help_requests' existing RLS (whatever it currently is) is
--    intentionally NOT modified by this migration — see header note.
--    reviews/business_hours' RLS-disabled status is a separate, carried-
--    forward, unremediated finding and is also NOT touched here.
--
--    All four new tables: RLS enabled, default-deny. service_role
--    bypasses RLS entirely (standard Supabase/Postgres behavior) and is
--    therefore not granted any explicit policy below — every write in
--    Migration 1 happens exclusively via service_role, server-side, per
--    Section J / B1. Only read policies for the owning profile are
--    defined for authenticated users; no INSERT/UPDATE/DELETE policy is
--    created for any non-service_role role in Migration 1.
-- -----------------------------------------------------------------------------

ALTER TABLE whatsapp_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE contributions ENABLE ROW LEVEL SECURITY;

-- whatsapp_identities: service_role only for every operation (contains
-- phone numbers). No policy is added for anon/authenticated — RLS's
-- default-deny already achieves "service_role only" since service_role
-- bypasses RLS regardless of policies present.

-- conversations: owning profile may SELECT their own conversations.
CREATE POLICY conversations_select_own ON conversations
  FOR SELECT
  USING (
    profile_id IN (SELECT id FROM profiles WHERE user_id = auth.uid())
  );

-- conversation_messages: owning profile may SELECT messages within their
-- own conversations. Append-only — no UPDATE/DELETE policy for anyone
-- other than service_role.
CREATE POLICY conversation_messages_select_own ON conversation_messages
  FOR SELECT
  USING (
    conversation_id IN (
      SELECT c.id
      FROM conversations c
      JOIN profiles p ON p.id = c.profile_id
      WHERE p.user_id = auth.uid()
    )
  );

-- contributions: contributor may SELECT their own contributions. Broader
-- public read of `verified` rows is an explicitly later decision, not
-- Migration 1 (Section J).
CREATE POLICY contributions_select_own ON contributions
  FOR SELECT
  USING (
    contributor_profile_id IN (SELECT id FROM profiles WHERE user_id = auth.uid())
  );

-- -----------------------------------------------------------------------------
-- 7. Community bootstrap (Section A3) — idempotent DML on the existing,
--    canonical `communities` table. No new community table. Safe to
--    re-run: only inserts a (name, city, country) combination that does
--    not already exist (communities has no unique constraint on these
--    columns, so this guard is done explicitly rather than relying on
--    ON CONFLICT).
-- -----------------------------------------------------------------------------

INSERT INTO communities (name, city, country, description, latitude, longitude)
SELECT v.name, v.city, v.country, v.description, v.latitude, v.longitude
FROM (
  VALUES
    ('Harare',   'Harare',   'Zimbabwe', 'TrustHub Connect pilot community', -17.8292::double precision, 31.0522::double precision),
    ('Chinhoyi', 'Chinhoyi', 'Zimbabwe', 'TrustHub Connect pilot community', -17.3667::double precision, 30.2000::double precision)
) AS v(name, city, country, description, latitude, longitude)
WHERE NOT EXISTS (
  SELECT 1 FROM communities c
  WHERE c.name = v.name AND c.city = v.city AND c.country = v.country
);

COMMIT;

