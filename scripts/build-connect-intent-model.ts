/**
 * Trains TrustHub Connect's offline intent model from the labelled Wisdom
 * dataset and writes lib/connect/intent-classifier.generated.ts.
 *
 * Run: node --experimental-strip-types scripts/build-connect-intent-model.ts
 *
 * Prints held-out accuracy on the dataset's `test` split, both for the exact
 * intent and for the route the intent leads to. The shipped model is trained
 * on every row, so production has the most data.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { distribution, tokenize, type IntentModel } from "../lib/connect/intent-classifier.ts";
import { INTENT_ROUTE } from "../lib/connect/intent-routes.ts";

interface DatasetRow { utterance: string; intent: string; split: string }

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "lib/contributions/dataset-input/wisdom_understanding_dataset_10k (1).jsonl");
const output = join(root, "lib/connect/intent-classifier.generated.ts");

export function train(rows: readonly DatasetRow[]): IntentModel {
  const intents = [...new Set(rows.map((row) => row.intent))].sort();
  const index = new Map(intents.map((intent, i) => [intent, i]));
  const docCount = new Array<number>(intents.length).fill(0);
  const tokenTotals = new Array<number>(intents.length).fill(0);
  const counts = new Map<string, Map<number, number>>();
  for (const row of rows) {
    const i = index.get(row.intent)!;
    docCount[i] += 1;
    for (const token of tokenize(row.utterance)) {
      tokenTotals[i] += 1;
      const perIntent = counts.get(token) ?? new Map<number, number>();
      perIntent.set(i, (perIntent.get(i) ?? 0) + 1);
      counts.set(token, perIntent);
    }
  }
  const tokens: Record<string, [number, number][]> = {};
  for (const [token, perIntent] of counts) tokens[token] = [...perIntent.entries()].sort((a, b) => a[0] - b[0]);
  return { intents, docCount, tokenTotals, vocabulary: counts.size, rows: rows.length, tokens };
}

function evaluate(model: IntentModel, rows: readonly DatasetRow[]): { exact: number; route: number; routable: number } {
  let exact = 0; let route = 0; let routable = 0;
  for (const row of rows) {
    const predicted = distribution(model, row.utterance)[0].intent;
    if (predicted === row.intent) exact += 1;
    if (INTENT_ROUTE[row.intent]) {
      routable += 1;
      if (INTENT_ROUTE[predicted] === INTENT_ROUTE[row.intent]) route += 1;
    }
  }
  return { exact, route, routable };
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const rows = readFileSync(source, "utf8").split("\n").filter(Boolean).map((line: string) => JSON.parse(line) as DatasetRow);
  const held = rows.filter((row: DatasetRow) => row.split === "test");
  const score = evaluate(train(rows.filter((row: DatasetRow) => row.split !== "test")), held);
  console.log(`Held-out test rows: ${held.length}`);
  console.log(`Exact intent accuracy: ${((score.exact / held.length) * 100).toFixed(1)}%`);
  console.log(`Route accuracy (routable rows): ${((score.route / score.routable) * 100).toFixed(1)}%`);
  const production = train(rows);
  writeFileSync(output, [
    "// Generated by scripts/build-connect-intent-model.ts from the labelled Wisdom dataset. Do not edit by hand.",
    `export const CONNECT_INTENT_MODEL = ${JSON.stringify(production)} as const;`,
    "",
  ].join("\n"));
  console.log(`Wrote ${output} (${production.intents.length} intents, ${production.vocabulary} words)`);
}
